         "        static let startCoverRadius: CGFloat = %d" % ps["startCoverRadius"],
         "        static let closeButton: CGFloat = %d" % ps["closeButton"],
         "        static let tabUnderline: CGFloat = %d" % ps["tabUnderline"]["height"],
