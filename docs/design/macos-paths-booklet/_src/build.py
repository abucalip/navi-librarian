def render(prefix):
    if not os.path.exists(CHROME):
        print("Google Chrome not found; PNGs skipped")
        return
    folder = os.path.join(OUT, "pages", "png")
    os.makedirs(folder, exist_ok=True)
    page = os.path.join(OUT, "pages", "mockups.html")
    for state, (width, height) in STATES.items():
        if prefix and not state.startswith(prefix):
            continue
        target = os.path.join(folder, state + ".png")
        subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                        "--window-size=%d,%d" % (width, height), "--virtual-time-budget=3000",
                        "--screenshot=%s" % target, "file://%s?only=%s" % (page, state)],
                       check=True, capture_output=True)
        print("wrote", os.path.relpath(target, OUT))


def main(argv):
    write_css()
    write_swift()
    print("wrote tokens.css, swift/CUPathsBooklet.swift")
    if "--no-png" in argv:
        return 0
    args = [a for a in argv if not a.startswith("--")]
    render(args[0] if args else "")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
