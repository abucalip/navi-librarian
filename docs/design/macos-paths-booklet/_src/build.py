#!/usr/bin/env python3
"""Builds the macOS Paths and Booklet design package from ../tokens.json.

Writes:
  ../tokens.css                 CSS variables the mockups draw with: --pb-* (Paths, Day and Night, default accent) and
                                --bk-* (Booklet, fixed), from the CU roles as cupalette.py builds them
  ../swift/CUPathsBooklet.swift the sizes and roles as Swift, for the implementing agent to copy (see its header)
  ../pages/png/<state>.png      one PNG per mockup state, rendered with Google Chrome (skipped when Chrome is missing)

    python3 build.py            # everything
    python3 build.py --no-png   # tokens.css and the Swift file only
    python3 build.py paths      # tokens, Swift and only the states whose id starts with "paths"

Spec: docs/plans/MACOS_PATHS_BOOKLET.md. Design tooling only: nothing imports it and no test collects it.
"""
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cupalette import hexs, make, mixed  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, ".."))
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
with open(os.path.join(OUT, "tokens.json"), encoding="utf-8") as handle:
    TOKENS = json.load(handle)

ROLE = {"CU.content": "content", "CU.text": "text", "CU.textSecondary": "textSecondary", "CU.separator": "separator",
        "CU.bgPanel": "panel", "CU.bgFill": "fill", "CU.accent": "accent", "CU.accentStrong": "accentStrong",
        "CU.accentTint": "accentTint", "CU.onAccent": "onAccent", "CU.success": "success", "CU.successTint": "successTint",
        "CU.separatorStrong": "separatorStrong", "CU.danger": "danger", "CU.shadowInk": None}

# The states drawn by pages/mockups.js, with the size of the PNG to take of each (window plus a margin).
STATES = {
    "paths-crew": (1100, 760), "paths-crew-night": (1100, 760), "paths-filter": (1100, 760),
    "paths-room": (1100, 760), "paths-gaps": (1100, 760), "paths-sonic": (1100, 760),
    "paths-loading": (1100, 420), "paths-failed": (1100, 420), "paths-empty": (1100, 420),
    "paths-artist-musician": (1100, 760), "paths-artist-sideman": (1100, 760), "paths-min": (880, 600),
    "booklet-spread": (1180, 820), "booklet-page": (1180, 820), "booklet-extra": (1180, 820),
    "booklet-single": (1180, 820), "booklet-pdf": (1180, 820), "booklet-loading": (1180, 820),
    "booklet-min": (820, 680),
}


def css_rgba(hexv, alpha):
    return "rgba(%d,%d,%d,%s)" % ((hexv >> 16) & 0xFF, (hexv >> 8) & 0xFF, hexv & 0xFF, ("%.2f" % alpha).rstrip("0").rstrip("."))


def kebab(name):
    return re.sub(r"(?<!^)(?=[A-Z0-9])", "-", name).lower()


def paths_vars(palette):
    lines = []
    for name, spec in TOKENS["paths_colors"].items():
        if name.startswith("_"):
            continue
        key = ROLE[spec["role"]]
        base = 0x000000 if key is None else palette[key]
        value = css_rgba(base, spec["opacity"]) if "opacity" in spec else hexs(base)
        lines.append("  --pb-%s: %s; /* %s%s */" % (kebab(name), value, spec["role"], " @ %s" % spec["opacity"] if "opacity" in spec else ""))
    return lines


def booklet_vars():
    lines = []
    stage = make("night")["accent"]
    for name, spec in TOKENS["booklet_colors"].items():
        if name.startswith("_") or not isinstance(spec, dict):
            continue
        if name == "stageAccent":
            value = hexs(stage)
        elif name == "selectedRow":
            value = hexs(mixed(int(TOKENS["booklet_colors"]["panel"]["hex"][1:], 16), stage, 0.18))
        elif "opacity" in spec:
            value = css_rgba(int(spec["hex"][1:], 16), spec["opacity"])
        else:
            value = spec["hex"]
        lines.append("  --bk-%s: %s;" % (kebab(name), value))
    return lines


def write_css():
    day, night = make("day"), make("night")
    out = ["/* Generated by _src/build.py from tokens.json. Do not edit by hand. */",
           "/* Paths: CU roles for Day (default) and Night with the default accent. In Swift use the CU roles, never these hex values. */",
           ":root, .pb-day {"] + paths_vars(day) + ["}", ".pb-night {"] + paths_vars(night) + ["}",
           "/* Booklet: fixed dark roles (CU.Booklet). stage-accent and selected-row are shown for the default accent. */",
           ":root {"] + booklet_vars() + [
           "  --pb-sans: -apple-system, BlinkMacSystemFont, \"SF Pro Text\", \"Helvetica Neue\", Arial, sans-serif;",
           "  --pb-display: -apple-system, BlinkMacSystemFont, \"SF Pro Display\", \"Helvetica Neue\", Arial, sans-serif;",
           "  --pb-mono: ui-monospace, \"SF Mono\", Menlo, monospace;", "}"]
    # CU.Font roles as classes, so the mockups use the role sizes and not the first drawing's.
    roles = {"eyebrow": (11, 16, 700, ".06em", True), "title2": (20, 24, 700, "-0.2px", False), "title3": (17, 24, 600, "-0.1px", False),
             "headline": (13, 20, 600, "0", False), "body": (13, 20, 400, "0", False), "callout": (12, 18, 400, "0", False),
             "caption": (11, 16, 400, "0", False)}
    for name, (size, line, weight, track, caps) in roles.items():
        out.append(".t-%s { font: %d %dpx/%dpx var(--pb-sans); letter-spacing: %s;%s }"
                   % (name, weight, size, line, track, " text-transform: uppercase;" if caps else ""))
    with open(os.path.join(OUT, "tokens.css"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(out) + "\n")


def swift_size(v):
    if isinstance(v, list) and len(v) == 2:
        return "CGSize(width: %s, height: %s)" % (v[0], v[1])
    return None


